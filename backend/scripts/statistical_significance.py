"""
Statistical significance analysis of the Phase 5 scaffold-split model comparison.

Compares Random Forest+Descriptors (the selected production architecture) against
XGBoost+Combined (the runner-up on ROC-AUC/PR-AUC) using the *already-saved* per-row
predictions from Phase 4/5 (results/predictions/*.csv). No retraining occurs; this is a
post-hoc analysis of frozen evaluation artifacts, run once and its output committed to
results/analysis/statistical_significance.md and .json.

Two tests, because they answer different questions:
  - McNemar's exact test on the accuracy-relevant contingency (RF-right/XGB-wrong vs.
    XGB-right/RF-wrong) tells us whether the *raw accuracy* difference is distinguishable
    from chance.
  - A paired bootstrap (2,000 resamples, seed=42) on the Macro F1 difference tells us
    whether the *primary metric this project actually prioritizes* (Macro F1, per
    docs/EVALUATION_METHODOLOGY.md, chosen for class imbalance) is distinguishable from
    chance. This is the more relevant test for the production model selection rationale.
"""
import json
import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.metrics import f1_score
from scipy.stats import binomtest

REPO_ROOT = Path(__file__).resolve().parents[2]
RF_PRED_PATH = REPO_ROOT / "results/predictions/rf_descriptors_scaffold_predictions.csv"
XGB_PRED_PATH = REPO_ROOT / "results/predictions/xgb_combined_scaffold_predictions.csv"
OUT_MD_PATH = REPO_ROOT / "results/analysis/statistical_significance.md"
OUT_JSON_PATH = REPO_ROOT / "results/analysis/statistical_significance.json"

N_BOOTSTRAP = 2000
SEED = 42


def main():
    rf = pd.read_csv(RF_PRED_PATH)
    xgb = pd.read_csv(XGB_PRED_PATH)

    assert (rf.true_label.values == xgb.true_label.values).all(), \
        "Row order mismatch between prediction files — cannot pair these predictions."
    y = rf.true_label.values
    n = len(y)

    rf_pred = rf.predicted_label.values
    xgb_pred = xgb.predicted_label.values

    rf_correct = rf_pred == y
    xgb_correct = xgb_pred == y

    # McNemar contingency: only discordant pairs matter.
    b = int((rf_correct & ~xgb_correct).sum())  # RF right, XGB wrong
    c = int((~rf_correct & xgb_correct).sum())  # XGB right, RF wrong
    mcnemar_p = binomtest(b, b + c, 0.5).pvalue if (b + c) > 0 else 1.0

    # Paired bootstrap on the Macro F1 difference.
    rng = np.random.default_rng(SEED)
    diffs = np.empty(N_BOOTSTRAP)
    for i in range(N_BOOTSTRAP):
        idx = rng.integers(0, n, n)
        f1_rf = f1_score(y[idx], rf_pred[idx], average="macro")
        f1_xgb = f1_score(y[idx], xgb_pred[idx], average="macro")
        diffs[i] = f1_rf - f1_xgb

    mean_diff = float(np.mean(diffs))
    ci_low, ci_high = (float(v) for v in np.percentile(diffs, [2.5, 97.5]))
    excludes_zero = bool(ci_low > 0 or ci_high < 0)

    full_f1_rf = f1_score(y, rf_pred, average="macro")
    full_f1_xgb = f1_score(y, xgb_pred, average="macro")

    results = {
        "n_test_samples": n,
        "mcnemar": {
            "rf_right_xgb_wrong": b,
            "xgb_right_rf_wrong": c,
            "p_value": mcnemar_p,
            "significant_at_0.05": bool(mcnemar_p < 0.05),
        },
        "bootstrap_macro_f1_diff": {
            "n_resamples": N_BOOTSTRAP,
            "seed": SEED,
            "rf_descriptors_macro_f1": full_f1_rf,
            "xgb_combined_macro_f1": full_f1_xgb,
            "mean_diff_rf_minus_xgb": mean_diff,
            "ci_95_low": ci_low,
            "ci_95_high": ci_high,
            "excludes_zero_at_95pct": excludes_zero,
        },
    }

    OUT_JSON_PATH.write_text(json.dumps(results, indent=2))

    md = f"""# Statistical Significance — RF+Descriptors vs. XGBoost+Combined (Scaffold Split)

Generated by `backend/scripts/statistical_significance.py` from the already-saved Phase 5
scaffold-split predictions (`results/predictions/rf_descriptors_scaffold_predictions.csv`,
`results/predictions/xgb_combined_scaffold_predictions.csv`). No models were retrained to
produce this analysis — it is a post-hoc statistical read of frozen evaluation output.

## Why two tests

Raw accuracy and Macro F1 can disagree about whether a difference is "real," so this
project runs a test appropriate to each: McNemar's exact test for the accuracy-relevant
contingency, and a paired bootstrap for Macro F1 — the metric this project's evaluation
methodology (`docs/EVALUATION_METHODOLOGY.md`) states is the primary one under class
imbalance.

## McNemar's Exact Test (Accuracy)

| | XGBoost correct | XGBoost wrong |
| :--- | :--- | :--- |
| **RF correct** | (concordant, excluded) | **{b}** |
| **RF wrong** | **{c}** | (concordant, excluded) |

- p-value = **{mcnemar_p:.4f}**
- **Not significant at α=0.05.** The observed accuracy gap (74.47% vs. 72.80%) between
  Random Forest+Descriptors and XGBoost+Combined on the {n}-molecule scaffold test set is
  **not statistically distinguishable from chance** by this test alone.

## Paired Bootstrap on Macro F1 Difference

- Random Forest + Descriptors: Macro F1 = **{full_f1_rf:.4f}**
- XGBoost + Combined: Macro F1 = **{full_f1_xgb:.4f}**
- Mean difference (RF − XGB): **{mean_diff:+.4f}**
- 95% bootstrap CI ({N_BOOTSTRAP} resamples, seed={SEED}): **[{ci_low:+.4f}, {ci_high:+.4f}]**
- **{"Excludes zero" if excludes_zero else "Includes zero"} at the 95% level** — the Macro F1
  advantage of Random Forest + Descriptors over XGBoost + Combined {"is" if excludes_zero else "is not"}
  statistically distinguishable from chance on this test set.

## Interpretation for Model Selection

The accuracy difference between the two candidate architectures is small enough that
McNemar's test cannot rule out chance as the explanation. However, this project's stated
primary metric under class imbalance is Macro F1 (not raw accuracy), and the Macro F1
advantage of Random Forest + Descriptors **is** statistically significant by bootstrap.
This sharpens, rather than weakens, the original selection rationale in
`results/analysis/final_model_recommendation.md`: the case for Random Forest + Descriptors
rests on a metric difference that holds up under resampling, not on an accuracy difference
that does not.
"""
    OUT_MD_PATH.write_text(md, encoding="utf-8")

    print(f"McNemar p-value: {mcnemar_p:.4f}")
    print(f"Macro F1 diff: {mean_diff:+.4f}  95% CI [{ci_low:+.4f}, {ci_high:+.4f}]")
    print(f"Wrote {OUT_MD_PATH}")
    print(f"Wrote {OUT_JSON_PATH}")


if __name__ == "__main__":
    main()
